// Writes docs/owner/BANGLA_REVIEW_SHEET.md: every user-visible Bangla string of src/i18n/packs.ts, grouped by screen,
// with the English source beside it, so a reviewer can mark OK or write a change. Run: node tools/bangla_review_sheet.mjs
// (Node 22+ reads the TypeScript file directly.) The sheet is generated: change the strings in packs.ts, then run this again.
import { writeFileSync, mkdirSync } from "node:fs";

const { PACKS } = await import("../src/i18n/packs.ts");
const { en, bn } = PACKS;

// key prefix -> [screen group, order]
const GROUPS = [
  ["First start and onboarding", ["mode", "onb", "lazy", "app", "lang", "logo"]],
  ["Today and Home", ["home", "next", "advice", "remind", "fresh", "reward", "tri", "arc", "grid"]],
  ["Journey: goals, stages, horizon", ["stage", "goals", "goal", "horizon", "smart", "swot", "overall", "funnel", "wheel", "univ", "journey", "week", "review", "report", "hist", "reality", "log", "dec", "legs", "leak", "fit"]],
  ["Plan, tasks, habits, focus", ["chart", "plan", "task", "habits", "focus", "stuck", "capture", "cards", "suggest"]],
  ["Money, risk, ventures, team", ["money", "risk", "ven", "team", "mm"]],
  ["Diary and intake", ["diary", "intake", "assess", "entry", "help", "importance", "requirement", "purpose", "privacy", "access", "label", "unknown", "empty", "ns", "badge", "fields", "glossary", "dict"]],
  ["Deen", ["deen"]],
  ["Topics and library", ["topics", "library", "rules", "halal"]],
  ["More: data, backup, lock, connections", ["more", "data", "backup", "enc", "snap", "store", "lock", "imp", "csv", "conn", "save", "cap", "status", "design", "view", "safety", "disclaimer"]],
  ["Navigation and accessibility", ["nav", "a11y"]],
];
const groupOf = (key) => { const p = key.split(".")[0]; for (const [name, ps] of GROUPS) if (ps.includes(p)) return name; return "Other"; };

const cell = (s) => String(s ?? "").replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, " <br> ");
const byGroup = new Map([...GROUPS.map(([n]) => [n, []]), ["Other", []]]);
for (const key of Object.keys(en)) byGroup.get(groupOf(key)).push(key);

let total = 0; const parts = [];
for (const [name, keys] of byGroup) {
  if (!keys.length) continue;
  total += keys.length;
  parts.push(`\n## ${name} (${keys.length})\n\n| # | Key | English (source) | বাংলা (to review) | OK / Change to |\n|---|---|---|---|---|`);
  keys.sort().forEach((k, i) => parts.push(`| ${i + 1} | \`${k}\` | ${cell(en[k])} | ${cell(bn[k])} |  |`));
}

const head = `# Bangla review sheet

Generated by \`node tools/bangla_review_sheet.mjs\` from \`src/i18n/packs.ts\`. **${total} strings**, grouped by screen. Do not edit this file by hand: mark your answers in a copy, send it back, and the builder applies the changes in \`packs.ts\` and generates this sheet again.

**For the reviewer (বাংলা):** প্রতিটি লাইনের শেষ ঘরে লিখুন **OK**, অথবা ঠিক করা বাংলা লেখাটি। শুধু বাংলা কলাম দেখুন; ইংরেজি কলাম বোঝার জন্য।
**For the reviewer (English):** In the last column write **OK**, or write the corrected Bangla. Review the Bangla column; English is only there for meaning.

## Rules to check each line against
1. Plain, polite, professional standard Bangla. No slang, no imitation of casual speech.
2. Everyday words people already say in English use the English word in Bangla script (for example স্টাফ, লোন, স্কিল, ইনকাম). Deen terms and words people really say stay Bangla (নামাজ, রোজা, যাকাত, দিন, টাকা). Full list: \`docs/design/bangla-loanword-swaps.md\`.
3. Numbers are Latin digits (0-9), never Bangla digits.
4. No red or punishing wording for missed goals. No score, rank, grade or streak words.
5. "Demo" and "real" data names stay clear; "যাচাই হয়নি" (unreviewed) stays on draft Bangla.
6. Not a fatwa: religious lines only point to a qualified person. No scripture text in the app.
7. Mix mode is made automatically from the Bangla column (common words switch to English), so fixing the Bangla column fixes Mix too.

## Not in this sheet yet
Field catalog help text (\`src/catalog/\`), glossary terms, topic and tip text (\`src/library/\`, \`public/content/\`), ready systems and demo data are stored outside \`packs.ts\`. They get their own sheet after this one is reviewed.

## Reviewer sign-off
Reviewer name: ______  Date: ______  Result: all OK / changes listed above   (TM-TST-161 changes from Partial only after a named person signs here.)
`;
mkdirSync("docs/owner", { recursive: true });
writeFileSync("docs/owner/BANGLA_REVIEW_SHEET.md", head + parts.join("\n") + "\n");
console.log(`wrote docs/owner/BANGLA_REVIEW_SHEET.md: ${total} strings in ${[...byGroup].filter(([, k]) => k.length).length} groups`);
