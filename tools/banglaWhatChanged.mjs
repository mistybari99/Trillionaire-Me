// Builds docs/owner/BANGLA_WHAT_CHANGED.md (short before/after list for the owner) from the change log written by bangla_plain_apply.mjs.
import { readFileSync, writeFileSync } from "node:fs";
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const show = (t, find) => { // keep long lines readable: cut around the first changed place
  const s = String(t); if (s.length <= 90) return s;
  const i = find ? Math.max(0, s.indexOf(find) - 25) : 0; return (i > 0 ? "…" : "") + s.slice(i, i + 90) + "…";
};
export function write(logPath, cfg) {
  const log = JSON.parse(readFileSync(logPath, "utf8"));
  const stepsDone = [...new Set(log.map((l) => l.step))];
  const byRule = new Map();
  for (const l of log) for (const id of l.rules) { if (!byRule.has(id)) byRule.set(id, []); byRule.get(id).push(l); }
  const out = [];
  out.push("# বাংলা লেখায় কী বদলেছে / What changed in the Bangla text", "",
    "সব বাংলা এখনো **যাচাই হয়নি** (reviewer sign-off পরে, TM-TST-161). এই তালিকা ছোট করে রাখা হয়েছে: আগে → পরে.",
    "Generated by `node tools/bangla_plain_apply.mjs --what-changed` from `docs/design/bangla-plain-change-log.json`. Rules: `docs/design/bangla-plain-final-decision.md`.", "",
    `Steps applied: ${stepsDone.join(", ")}. Strings changed: ${log.length}.`, "",
    "## 1. Word changes (everywhere in the app)", "", "| আগে | পরে | কতগুলো লেখায় | উদাহরণ |", "|---|---|---|---|");
  for (const r of cfg.rules) {
    const hits = byRule.get(r.id) || []; if (!hits.length) continue;
    const label = r.type === "digits" ? "বাংলা সংখ্যা (০-৯)" : r.from; const to = r.type === "digits" ? "0-9" : r.to;
    const ex = hits.find((h) => !h.protected) || hits[0];
    out.push(`| ${cell(label)} | ${cell(to)} | ${hits.length} | ${cell(show(ex.after, r.type === "digits" ? "" : r.to))} |`);
  }
  out.push("", "## 2. Single lines rewritten (by screen)", "");
  const screens = [...new Set(cfg.rewrites.map((w) => w.screen))];
  for (const sc of screens) {
    const items = cfg.rewrites.filter((w) => w.screen === sc && byRule.get(w.id));
    if (!items.length) continue;
    out.push(`### ${sc}`, "", "| আগে | পরে | কেন |", "|---|---|---|");
    for (const w of items) {
      const l = byRule.get(w.id)[0];
      out.push(`| ${cell(show(l.before, w.expect))} | ${cell(w.to)} | ${cell(w.note || "সহজ ভাষা")} |`);
    }
    out.push("");
  }
  const prot = log.filter((l) => l.protected);
  out.push("## 3. Protected lines", "", `${prot.length} protected lines (D-B consent and delete warnings, ফতোয়া নয়, গ্যারান্টি, Unknown, privacy, permission) changed **spelling only** (এই লেখার অর্থ বদলায়নি, শুধু বানান ঠিক করা হয়েছে). Examples:`, "");
  for (const l of prot.slice(0, 6)) out.push(`- \`${l.key}\`: ${show(l.before)} → ${show(l.after)}`);
  out.push("", "## 4. Not changed on purpose", "", "ব্যক্তিগত, গোনা, মাপকাঠি, বিরতি, ন্যূনতম, সর্বোচ্চ, সর্বশেষ, আনুমানিক, সম্পন্ন, নির্ধারিত, শর্ত, সব Deen শব্দ (নামাজ, রোজা, যাকাত, দিন, টাকা). Reason: everyday words, or protected meaning.", "",
    "## 5. Undo", "", "প্রতিটি ধাপ একটি commit. `git revert <commit>` দিয়ে ফেরানো যায়. Rule `গোল` (লক্ষ্য থেকে) ফেরাতে: DECISIONS_LOG-এ undo steps দেখুন.");
  writeFileSync("docs/owner/BANGLA_WHAT_CHANGED.md", out.join("\n") + "\n");
  console.log(`wrote docs/owner/BANGLA_WHAT_CHANGED.md (${out.length} lines)`);
}
