// Builds docs/owner/BANGLA_WHAT_CHANGED.md (short before/after list for the owner) from the change log written by bangla_plain_apply.mjs.
// Part 1 = pass 1 (3 Nov 2026, groups spelling/meaning/stiff). Part 2 = pass 2 (spoken Bangla, groups p2words/p2screens/p2left).
import { readFileSync, writeFileSync } from "node:fs";
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const show = (t, find) => { // keep long lines readable: cut around the first changed place
  const s = String(t); if (s.length <= 90) return s;
  const i = find ? Math.max(0, s.indexOf(find) - 25) : 0; return (i > 0 ? "…" : "") + s.slice(i, i + 90) + "…";
};
const PASSES = [
  { n: 1, title: "Pass 1: spelling, wrong meanings, stiff words (3 Nov 2026)", groups: ["spelling", "meaning", "stiff"] },
  { n: 2, title: "Pass 2: plain spoken Bangla (3 Nov 2026)", groups: ["p2words", "p2screens", "p2left"] },
];
export function write(logPath, cfg) {
  const log = JSON.parse(readFileSync(logPath, "utf8"));
  const byRule = new Map();
  for (const l of log) for (const id of l.rules) { if (!byRule.has(id)) byRule.set(id, []); byRule.get(id).push(l); }
  const out = [];
  out.push("# বাংলা লেখায় কী বদলেছে / What changed in the Bangla text", "",
    "সব বাংলা এখনো **যাচাই হয়নি** (reviewer sign-off পরে, TM-TST-161). এই তালিকা ছোট করে রাখা হয়েছে: আগে → পরে. প্রথমে pass 1, তারপর pass 2.",
    "Generated by `node tools/bangla_plain_apply.mjs --what-changed` from `docs/design/bangla-plain-change-log.json`. Rules: `docs/design/bangla-plain-final-decision.md` (pass 1) and `docs/design/bangla-plain-pass2.md` (pass 2).", "");
  for (const P of PASSES) {
    const entries = log.filter((l) => P.groups.includes(l.group));
    if (!entries.length) continue;
    const steps = [...new Set(entries.map((l) => l.step))];
    out.push(`# ${P.title}`, "", `Steps applied: ${steps.join(", ")}. Strings changed: ${entries.length}.`, "",
      `## ${P.n}.1 Word changes (everywhere in the app)`, "", "| আগে | পরে | কতগুলো লেখায় | উদাহরণ |", "|---|---|---|---|");
    for (const r of cfg.rules.filter((x) => P.groups.includes(x.group))) {
      const hits = byRule.get(r.id) || []; if (!hits.length) continue;
      const label = r.type === "digits" ? "বাংলা সংখ্যা (০-৯)" : r.from; const to = r.type === "digits" ? "0-9" : r.to;
      const ex = hits.find((h) => !h.protected) || hits[0];
      out.push(`| ${cell(label)} | ${cell(to)} | ${hits.length} | ${cell(show(ex.after, r.type === "digits" ? "" : r.to))} |`);
    }
    out.push("", `## ${P.n}.2 Single lines rewritten (by screen)`, "");
    const rws = cfg.rewrites.filter((w) => P.groups.includes(w.group));
    for (const sc of [...new Set(rws.map((w) => w.screen))]) {
      const items = rws.filter((w) => w.screen === sc && byRule.get(w.id));
      if (!items.length) continue;
      out.push(`### ${sc}`, "", "| আগে | পরে | কেন |", "|---|---|---|");
      for (const w of items) {
        const l = byRule.get(w.id)[0];
        out.push(`| ${cell(show(l.before, w.expect))} | ${cell(show(l.after, w.to))} | ${cell(w.note || "সহজ ভাষা")} |`);
      }
      out.push("");
    }
    const prot = entries.filter((l) => l.protected);
    out.push(`## ${P.n}.3 Protected lines`, "", `${prot.length} protected lines (D-B consent and delete warnings, ফতোয়া নয়, গ্যারান্টি, Unknown, privacy, permission) changed **spelling or naming only** (অর্থ বদলায়নি; যেমন এটি → এটা, সঙ্গে → সাথে). Examples:`, "");
    for (const l of prot.slice(0, 6)) out.push(`- \`${l.key}\`: ${show(l.before)} → ${show(l.after)}`);
    out.push("");
  }
  out.push("# Not changed on purpose", "",
    "- Pass 1 left: ব্যক্তিগত, গোনা, মাপকাঠি, বিরতি, ন্যূনতম, সর্বোচ্চ, সর্বশেষ, আনুমানিক, সম্পন্ন, নির্ধারিত. Pass 2 changed them (owner, 3 Nov 2026) except where a Deen definition or a protected line needs the old word.",
    "- Deen শব্দ: নামাজ, রোজা, যাকাত, দিন, টাকা, নিসাব, আলেম; রোজার সংজ্ঞায় \"নির্ধারিত সময়ে\"; ফিতরার সংজ্ঞায় \"নির্ধারিত দান\". হাদিসের লেখা কোনো বদল হয়নি.",
    "- \"যাচাই হয়নি\" ট্যাগ, ফতোয়া নয়, গ্যারান্টি/প্রতিশ্রুতি নেই, জানা নেই ≠ 0, শাস্তির ভাষা নেই, টাইপ করে নিশ্চিত করার শব্দ, D-B সম্মতি ও ডিলিটের সতর্কতা (\"ফেরানো যায় না\"), D-C লেখা: শুধু বানান/নাম (এটি → এটা, সঙ্গে → সাথে) বদলেছে.",
    "- \"দিন গোনা\" (streak নেই বোঝাতে), হাতে গোনা (গুনে), মূল্যবোধ, মূল্যায়ন (কয়েকটি জায়গা বাদে), ব্যক্তি (Deen disclaimer-এ).", "",
    "# Undo", "", "প্রতিটি ধাপ একটি commit. `git revert <commit>` দিয়ে ফেরানো যায়. Pass 2 undo: DECISIONS_LOG-এর \"Bangla plain pass 2\" entry দেখুন (তিনটি commit revert করলেই পুরোনো লেখা ফেরে).");
  writeFileSync("docs/owner/BANGLA_WHAT_CHANGED.md", out.join("\n") + "\n");
  console.log(`wrote docs/owner/BANGLA_WHAT_CHANGED.md (${out.length} lines)`);
}
